        print("  Creating initial stock (purchase invoices)...")
        batches: list[ProductBatch] = []
        # batch_stock[product_id][warehouse_id] = list of (batch_id, qty, unit_cost, expiry)
        batch_stock: dict[int, dict[int, list]] = {}

        today = date.today()
        purchase_data: list[dict] = []
        purchase_line_data: list[dict] = []
        purchase_counter = 0

        # Create 2 batches per product in main warehouse + 1 in each other warehouse
        for pidx, pid in enumerate(prod_ids):
            batch_stock.setdefault(pid, {})
            ws_price, _ = prod_prices[pid]
            unit_cost = (ws_price * Decimal("0.6")).quantize(TWO, ROUND_HALF_UP)
            for widx, wid in enumerate(wh_ids):
                batch_stock[pid].setdefault(wid, [])
                num_batches = 2 if widx == 0 else 1
                for b in range(num_batches):
                    qty = Decimal(str(random.randint(200, 800)))
                    exp = today + timedelta(days=random.randint(90, 730))
                    bn = f"B{pid:04d}-W{wid}-{b+1}"
                    purchase_counter += 1
                    batch_num = f"PUR-{purchase_counter:06d}"
                    batches.append(ProductBatch(
                        product_id=pid, warehouse_id=wid, batch_number=bn,
                        expiry_date=exp, quantity=qty, unit_cost=unit_cost,
                    ))

        session.add_all(batches)
        await session.flush()
        print(f"  ✓ Batches: {len(batches)}")

        # Build lookup: batch_stock[pid][wid] = [(batch_id, remaining_qty, unit_cost, expiry)]
        for b in batches:
            batch_stock[b.product_id][b.warehouse_id].append(
                [b.id, b.quantity, b.unit_cost, b.expiry_date]
            )
        # Sort each by expiry (FEFO)
        for pid in batch_stock:
            for wid in batch_stock[pid]:
                batch_stock[pid][wid].sort(key=lambda x: x[3])

        # --- 8. Sales Invoices (100/day for 365 days) ---
        print("  Creating sales invoices (100/day × 365 days)...")
        invoices: list[SalesInvoice] = []
        invoice_lines: list[SalesInvoiceLine] = []
